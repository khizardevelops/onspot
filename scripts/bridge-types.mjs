/**
 * Assembles the bridge's TypeScript types (P1).
 *
 * `ts-rs` writes one `.ts` file per type when `cargo test` runs the export
 * tests in `onspot-app` and `onspot-bridge`. Drivers want one file, so this
 * script concatenates those exports in a fixed order into
 * `src/lib/core-client/types.gen.ts`. The order is explicit so regeneration is
 * byte-identical; a missing export fails loudly instead of producing a partial
 * file.
 *
 * Run through `bun run bridge:types`, which runs the export tests first.
 */

import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const REPO_ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const BINDINGS_DIR = join(REPO_ROOT, 'src/lib/core-client/bindings');
const OUTPUT_PATH = join(REPO_ROOT, 'src/lib/core-client/types.gen.ts');

/** Fixed order: input types, then responses, then events. Do not sort dynamically. */
const TYPE_ORDER = [
	'BridgeError',
	'CoreConfig',
	'InitResponse',
	'PingRequest',
	'PingResponse',
	// P2 storage responses, in the order the screen consumes them.
	'SessionView',
	'SetupView',
	'AttemptPreviewView',
	'HistorySessionView',
	'HistoryResponse',
	'ChangedResponse',
	'SettingView',
	'SettingsResponse',
	'SettingValueResponse',
	// P3 practice view and commands.
	'EngineMode',
	'LlmEndpoint',
	'PracticeConfig',
	'PracticePhase',
	'TranslationBreakdownItem',
	'TranslationSet',
	'FollowUp',
	'PhraseGloss',
	'GlossedRange',
	'TextGlosses',
	'Attempt',
	'Correction',
	'ErrorView',
	'AttemptView',
	'ProgressView',
	'PracticeSnapshot',
	'PromptView',
	'PracticeResponse',
	'ResumeResponse',
	'OpenResponse',
	'AcceptedResponse',
	'TestConnectionResponse',
	'UiEvent'
];

const TS_RS_HEADER = /^\/\/ This file was generated[^\n]*\n+/;
/**
 * ts-rs writes one file per type and imports its neighbours by path. The
 * assembler concatenates them into one module, where those imports would point
 * at files that do not exist next to `types.gen.ts`.
 */
const TS_RS_IMPORT = /^import type \{[^}]*\} from "\.\/[^"]+";\n/gm;

const sections = TYPE_ORDER.map((typeName) => {
	const path = join(BINDINGS_DIR, `${typeName}.ts`);
	let source;
	try {
		source = readFileSync(path, 'utf8');
	} catch {
		throw new Error(`missing ${typeName}.ts: run \`cargo test -p onspot-app -p onspot-bridge export_bindings\` first`);
	}
	return source.replace(TS_RS_HEADER, '').replace(TS_RS_IMPORT, '').trimEnd();
});

const output = `// SPDX-License-Identifier: AGPL-3.0-or-later
//
// @generated by \`bun run bridge:types\` from the Rust types in
// \`crates/onspot-app\` and \`bindings/onspot-bridge\` (ts-rs). Do not edit this
// file by hand; change the Rust type and regenerate.

${sections.join('\n\n')}
`;

writeFileSync(OUTPUT_PATH, output);
console.log(`wrote src/lib/core-client/types.gen.ts (${TYPE_ORDER.length} types)`);
